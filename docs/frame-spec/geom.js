'use strict';

/**
 * 프레임 규격 한 곳. 가이드·예시·빈 틀이 모두 이 값을 읽는다.
 *
 * ── 종이와 캔버스가 다르다 ────────────────────────────────
 * 인화 용지는 100 x 148mm 이고, 캔버스는 4 x 6인치(101.6 x 152.4mm)다.
 * 가로 1.6mm · 세로 4.4mm 만큼 캔버스가 더 크다. 인화기가 용지에 맞추면서
 * 그만큼을 잘라내고, 여기에 인화기 자체 여백이 더 붙는다.
 *
 * 캔버스를 용지에 딱 맞추지 않는 이유는 앱이 4 x 6 비율로 사진을 잘라 두기
 * 때문이다. 캔버스만 바꾸면 화면에서 본 구도와 종이에 나온 구도가 어긋난다.
 *
 * ── 그래서 안전선을 둔다 ──────────────────────────────────
 * 사방 5mm 는 잘려나간다고 보고, 사진 칸과 로고를 그 안쪽에만 둔다.
 * 바탕색과 무늬는 안전선을 넘어 가장자리까지 채워도 된다 — 잘려도 그만이고,
 * 오히려 채우지 않으면 잘린 자리에 흰 테가 생긴다.
 */

const DPI = 300;
const mm = (v) => Math.round((v * DPI) / 25.4);

const G = {
  W: 1200, H: 1800, // 4 x 6인치 @300dpi

  /** 잘려나간다고 보는 사방 여유 — 5mm */
  SAFE: mm(5), // 59

  MX: 56,  // 안전선 안쪽 좌우 여백
  MY: 111, // 안전선 안쪽 위아래 여백
  GX: 90,  // 칸 사이 가로 간격
  GY: 100, // 칸 사이 세로 간격
  CW: 440, CH: 420,
};

/** 잘려도 남는 자리 */
G.safeBox = {
  x: G.SAFE,
  y: G.SAFE,
  w: G.W - G.SAFE * 2,
  h: G.H - G.SAFE * 2,
};

G.slots = [0, 1, 2, 3, 4].map((i) => {
  const col = i < 3 ? 0 : 1;
  const row = i < 3 ? i : i - 3;
  return {
    n: i + 1,
    x: G.SAFE + G.MX + col * (G.CW + G.GX),
    y: G.SAFE + G.MY + row * (G.CH + G.GY),
    w: G.CW, h: G.CH,
  };
});

G.brand = {
  x: G.SAFE + G.MX + (G.CW + G.GX),
  y: G.SAFE + G.MY + 2 * (G.CH + G.GY),
  w: G.CW, h: G.CH,
};

/** 가운데 세로 통로 */
G.channel = { x: G.SAFE + G.MX + G.CW, w: G.GX };

/** 실물 크기(mm)로 바꾼다 — 문서에 적을 때 쓴다 */
G.toMm = (px) => (px * 25.4) / DPI;
G.DPI = DPI;

module.exports = G;
