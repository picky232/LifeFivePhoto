'use strict';

/**
 * 프레임 규격 한 곳. 가이드·예시·빈 틀이 모두 이 값을 읽는다.
 *
 * ── 종이와 캔버스가 다르다 ────────────────────────────────
 * 인화 용지는 100 x 148mm 이고, 캔버스는 4 x 6인치(101.6 x 152.4mm)다.
 * 가로 1.6mm · 세로 4.4mm 만큼 캔버스가 더 크다. 인화기가 용지에 맞추면서
 * 그만큼을 잘라내고, 여기에 인화기 자체 여백이 더 붙는다.
 *
 * 캔버스를 용지에 딱 맞추지 않는 이유는 앱이 4 x 6 비율로 사진을 잘라 두기
 * 때문이다. 캔버스만 바꾸면 화면에서 본 구도와 종이에 나온 구도가 어긋난다.
 *
 * ── 테두리는 흰색으로 비운다 ──────────────────────────────
 * 위아래 7mm · 좌우 4mm 를 흰색으로 두고, 디자인은 그 안쪽에만 넣는다.
 * 위아래가 더 넓은 것은 세로로 더 많이 잘리기 때문이다 (4.4mm 대 1.6mm).
 *
 * 바탕을 가장자리까지 채우는 방식(도련)이 아니다. 인화기가 정확히 자르지
 * 못하면 채운 쪽은 잘린 자리가 그대로 보여 실수처럼 읽히는데, 흰 테는
 * 조금 틀어져도 원래 그런 디자인으로 보인다.
 */

const DPI = 300;
const mm = (v) => Math.round((v * DPI) / 25.4);

const G = {
  W: 1200, H: 1800, // 4 x 6인치 @300dpi

  /** 흰색으로 비워두는 테두리 */
  SAFE_X: mm(4), // 47  (좌우 4mm)
  SAFE_Y: mm(7), // 83  (위아래 7mm)

  MX: 58,  // 흰 테 안쪽 좌우 여백
  MY: 72,  // 흰 테 안쪽 위아래 여백
  GX: 90,  // 칸 사이 가로 간격
  GY: 100, // 칸 사이 세로 간격
  CW: 450, CH: 430,
};

/** 흰 테를 뺀 나머지 — 디자인이 들어가는 자리 */
G.safeBox = {
  x: G.SAFE_X,
  y: G.SAFE_Y,
  w: G.W - G.SAFE_X * 2,
  h: G.H - G.SAFE_Y * 2,
};

G.slots = [0, 1, 2, 3, 4].map((i) => {
  const col = i < 3 ? 0 : 1;
  const row = i < 3 ? i : i - 3;
  return {
    n: i + 1,
    x: G.SAFE_X + G.MX + col * (G.CW + G.GX),
    y: G.SAFE_Y + G.MY + row * (G.CH + G.GY),
    w: G.CW, h: G.CH,
  };
});

G.brand = {
  x: G.SAFE_X + G.MX + (G.CW + G.GX),
  y: G.SAFE_Y + G.MY + 2 * (G.CH + G.GY),
  w: G.CW, h: G.CH,
};

/** 가운데 세로 통로 */
G.channel = { x: G.SAFE_X + G.MX + G.CW, w: G.GX };

/** 실물 크기(mm)로 바꾼다 — 문서에 적을 때 쓴다 */
G.toMm = (px) => (px * 25.4) / DPI;
G.DPI = DPI;

module.exports = G;
